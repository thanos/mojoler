#!/usr/bin/env python3
"""Emit Mojo wrappers and Elixir stubs from tools/dsl/decls.json.

The declaration is data. This program does not evaluate it as code.
User Mojo stays in native/examples. Generated files stay in native/generated
and lib/mojoler/dsl.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEDULES = {"normal": "c_uint(0)", "dirty_cpu": "abi_dirty_cpu()", "dirty_io": "abi_dirty_io()"}
KINDS = {"add", "shift", "borrow_len", "open", "bump"}


def fail(message: str) -> None:
    print(f"dsl: {message}", file=sys.stderr)
    raise SystemExit(1)


def load(path: Path) -> dict:
    data = json.loads(path.read_text())
    seen = set()
    for module in data["modules"]:
        for fn in module["functions"]:
            schedule = fn["schedule"]
            if schedule not in SCHEDULES:
                fail(f"{module['module']}.{fn['name']} has schedule {schedule}, not one of {sorted(SCHEDULES)}")
            if fn["kind"] not in KINDS:
                fail(f"unsupported kind {fn['kind']}")
            if fn["ownership"] == "borrow" and schedule != "normal":
                fail(
                    f"{module['module']}.{fn['name']} borrows a call-local view "
                    f"across schedule {schedule}"
                )
            key = (module["module"], fn["name"], fn["arity"])
            if key in seen:
                fail(f"duplicate {key}")
            seen.add(key)
    return data


def lit_helpers() -> str:
    return """
def lit(text: StaticString) -> Pointer[c_char, ImmStaticOrigin]:
    return text.as_c_string_span().ptr()


def pair(env: Pointer[NoneType, MutUntrackedOrigin], a: c_ulong, b: c_ulong) -> c_ulong:
    var mem = must_alloc(c_size_t(16)).unsafe_bitcast[c_ulong]()
    mem[unsafe_offset=0] = a
    mem[unsafe_offset=1] = b
    var out = enif_make_tuple_from_array(env, mem, c_uint(2))
    must_free(mem)
    return out


def tagged(env: Pointer[NoneType, MutUntrackedOrigin], tag: StaticString, value: c_ulong) -> c_ulong:
    return pair(env, enif_make_atom(env, lit(tag)), value)
"""


def arith(module: dict) -> str:
    name = module["module"]
    user = module["user"]
    fn = module["functions"][0]
    flag = SCHEDULES[fn["schedule"]]
    return f"""# Generated by tools/dsl/generate.py. Do not edit.
# Declaration: {name}.add/2 schedule={fn['schedule']} ownership={fn['ownership']}

from std.ffi import c_char, c_int, c_long, c_size_t, c_uint, c_ulong

from mojoler.abi.otp_nif import (
    ErlNifEntry,
    ErlNifFunc,
    enif_get_long,
    enif_make_atom,
    enif_make_badarg,
    enif_make_long,
    enif_make_tuple_from_array,
)
from mojoler.abi.prim import alloc_funcs, make_entry, must_alloc, must_free
from {user} import AddResult, checked_add
{lit_helpers()}

def add(
    env: Pointer[NoneType, MutUntrackedOrigin],
    argc: c_int,
    argv: Pointer[c_ulong, MutUntrackedOrigin],
) abi("C") -> c_ulong:
    if argc != 2:
        return enif_make_badarg(env)
    var a = c_long(0)
    var b = c_long(0)
    if enif_get_long(env, argv[unsafe_offset=0], Pointer(to=a)) == 0:
        return enif_make_badarg(env)
    if enif_get_long(env, argv[unsafe_offset=1], Pointer(to=b)) == 0:
        return enif_make_badarg(env)
    var result = checked_add(a, b)
    if result.ok == 0:
        return tagged(env, "error", enif_make_atom(env, lit("overflow")))
    return tagged(env, "ok", enif_make_long(env, result.value))


@export("nif_init")
def nif_init() abi("C") -> Pointer[ErlNifEntry, MutUntrackedOrigin]:
    var funcs = alloc_funcs(1)
    funcs[] = ErlNifFunc(lit("add"), c_uint(2), add, {flag})
    return make_entry(lit("Elixir.{name}"), funcs, c_int(1), None, None, None, None)
"""


def bytes_mod(module: dict) -> str:
    name = module["module"]
    user = module["user"]
    flags = {fn["name"]: SCHEDULES[fn["schedule"]] for fn in module["functions"]}
    return f"""# Generated by tools/dsl/generate.py. Do not edit.
# shift copies the payload. borrow_len refuses a non-binary instead of copying.

from std.ffi import c_char, c_int, c_long, c_size_t, c_uint, c_ulong
from std.sys import size_of

from mojoler.abi.otp_nif import (
    ErlNifBinary,
    ErlNifEntry,
    ErlNifFunc,
    enif_get_long,
    enif_inspect_binary,
    enif_make_atom,
    enif_make_badarg,
    enif_make_long,
    enif_make_new_binary,
    enif_make_tuple_from_array,
)
from mojoler.abi.prim import alloc_funcs, make_entry, must_alloc, must_free
from {user} import borrowed_len, shift_byte
{lit_helpers()}

def shift(
    env: Pointer[NoneType, MutUntrackedOrigin],
    argc: c_int,
    argv: Pointer[c_ulong, MutUntrackedOrigin],
) abi("C") -> c_ulong:
    if argc != 1:
        return enif_make_badarg(env)
    var inspected = must_alloc(c_size_t(size_of[ErlNifBinary]())).unsafe_bitcast[ErlNifBinary]()
    if enif_inspect_binary(env, argv[unsafe_offset=0], inspected) == 0:
        must_free(inspected)
        return tagged(env, "error", enif_make_atom(env, lit("not_binary")))
    var n = Int(inspected[].size)
    var owned = must_alloc(c_size_t(n if n > 0 else 1))
    var i = 0
    while i < n:
        owned[unsafe_offset=i] = shift_byte(inspected[].data[unsafe_offset=i])
        i += 1
    must_free(inspected)
    var term = c_ulong(0)
    var out = enif_make_new_binary(env, c_size_t(n), Pointer(to=term))
    i = 0
    while i < n:
        out[unsafe_offset=i] = owned[unsafe_offset=i]
        i += 1
    must_free(owned)
    var mem = must_alloc(c_size_t(24)).unsafe_bitcast[c_ulong]()
    mem[unsafe_offset=0] = enif_make_atom(env, lit("ok"))
    mem[unsafe_offset=1] = term
    mem[unsafe_offset=2] = enif_make_long(env, c_long(n))
    var triple = enif_make_tuple_from_array(env, mem, c_uint(3))
    must_free(mem)
    return triple


def borrow_len(
    env: Pointer[NoneType, MutUntrackedOrigin],
    argc: c_int,
    argv: Pointer[c_ulong, MutUntrackedOrigin],
) abi("C") -> c_ulong:
    if argc != 1:
        return enif_make_badarg(env)
    var inspected = must_alloc(c_size_t(size_of[ErlNifBinary]())).unsafe_bitcast[ErlNifBinary]()
    if enif_inspect_binary(env, argv[unsafe_offset=0], inspected) == 0:
        must_free(inspected)
        return tagged(env, "error", enif_make_atom(env, lit("not_binary")))
    var n = borrowed_len(c_int(inspected[].size))
    must_free(inspected)
    return tagged(env, "ok", enif_make_long(env, c_long(n)))


@export("nif_init")
def nif_init() abi("C") -> Pointer[ErlNifEntry, MutUntrackedOrigin]:
    var funcs = alloc_funcs(2)
    funcs[unsafe_offset=0] = ErlNifFunc(lit("shift"), c_uint(1), shift, {flags["shift"]})
    funcs[unsafe_offset=1] = ErlNifFunc(lit("borrow_len"), c_uint(1), borrow_len, {flags["borrow_len"]})
    return make_entry(lit("Elixir.{name}"), funcs, c_int(2), None, None, None, None)
"""


def box(module: dict) -> str:
    name = module["module"]
    user = module["user"]
    return f"""# Generated by tools/dsl/generate.py. Do not edit.
# Resource boilerplate is generated. native/examples/box_user.mojo is the step.

from std.ffi import c_char, c_int, c_long, c_size_t, c_uint, c_ulong, external_call
from std.sys import size_of

from mojoler.abi.otp_nif import (
    ErlNifEntry,
    ErlNifFunc,
    enif_alloc_resource,
    enif_get_long,
    enif_get_resource,
    enif_make_badarg,
    enif_make_long,
    enif_make_resource,
    enif_priv_data,
    enif_release_resource,
)
from mojoler.abi.prim import alloc_funcs, callback_opt, make_entry, must_alloc, must_free
from {user} import step


def lit(text: StaticString) -> Pointer[c_char, ImmStaticOrigin]:
    return text.as_c_string_span().ptr()


@fieldwise_init
struct Slot(RegisterPassable):
    var value: c_long


def dtor(
    env: Pointer[NoneType, MutUntrackedOrigin], obj: Pointer[NoneType, MutUntrackedOrigin]
) abi("C"):
    _ = env
    _ = obj


def load(
    env: Pointer[NoneType, MutUntrackedOrigin],
    priv: Pointer[Pointer[NoneType, MutUntrackedOrigin], MutUntrackedOrigin],
    _info: c_ulong,
) abi("C") -> c_int:
    var tried = c_int(0)
    var kind = external_call["enif_open_resource_type", Pointer[NoneType, MutUntrackedOrigin]](
        env, lit("Elixir.{name}"), lit("box"), dtor, c_int(1), Pointer(to=tried)
    )
    var box = must_alloc(c_size_t(8))
    box.unsafe_bitcast[Pointer[NoneType, MutUntrackedOrigin]]()[] = kind
    priv[] = box.unsafe_bitcast[NoneType]()
    return c_int(0)


def unload(
    env: Pointer[NoneType, MutUntrackedOrigin], priv: Pointer[NoneType, MutUntrackedOrigin]
) abi("C"):
    _ = env
    must_free(priv)


def kind_of(env: Pointer[NoneType, MutUntrackedOrigin]) -> Pointer[NoneType, MutUntrackedOrigin]:
    return enif_priv_data(env).unsafe_bitcast[Pointer[NoneType, MutUntrackedOrigin]]()[]


def open_box(
    env: Pointer[NoneType, MutUntrackedOrigin],
    argc: c_int,
    argv: Pointer[c_ulong, MutUntrackedOrigin],
) abi("C") -> c_ulong:
    _ = argv
    if argc != 0:
        return enif_make_badarg(env)
    var obj = enif_alloc_resource(kind_of(env), c_size_t(size_of[Slot]()))
    var body = obj.unsafe_bitcast[Slot]()
    body[] = Slot(c_long(0))
    var term = enif_make_resource(env, obj)
    enif_release_resource(obj)
    return term


def bump(
    env: Pointer[NoneType, MutUntrackedOrigin],
    argc: c_int,
    argv: Pointer[c_ulong, MutUntrackedOrigin],
) abi("C") -> c_ulong:
    if argc != 2:
        return enif_make_badarg(env)
    var slot = must_alloc(c_size_t(8))
    var box = slot.unsafe_bitcast[Pointer[NoneType, MutUntrackedOrigin]]()
    var rc = enif_get_resource(env, argv[unsafe_offset=0], kind_of(env), box)
    var obj = box[]
    must_free(slot)
    if rc == 0:
        return enif_make_badarg(env)
    var delta = c_long(0)
    if enif_get_long(env, argv[unsafe_offset=1], Pointer(to=delta)) == 0:
        return enif_make_badarg(env)
    var body = obj.unsafe_bitcast[Slot]()
    body[].value = step(body[].value, delta)
    return enif_make_long(env, body[].value)


@export("nif_init")
def nif_init() abi("C") -> Pointer[ErlNifEntry, MutUntrackedOrigin]:
    var funcs = alloc_funcs(2)
    funcs[unsafe_offset=0] = ErlNifFunc(lit("open"), c_uint(0), open_box, c_uint(0))
    funcs[unsafe_offset=1] = ErlNifFunc(lit("bump"), c_uint(2), bump, c_uint(0))
    var load_fn = load
    var unload_fn = unload
    return make_entry(
        lit("Elixir.{name}"),
        funcs,
        c_int(2),
        callback_opt(Pointer(to=load_fn).unsafe_bitcast[Int]()[]),
        None,
        None,
        callback_opt(Pointer(to=unload_fn).unsafe_bitcast[Int]()[]),
    )
"""


def elixir(module: dict) -> str:
    name = module["module"]
    lib = module["lib"]
    stubs = []
    for fn in module["functions"]:
        args = ", ".join("_" for _ in range(fn["arity"]))
        if fn["arity"] == 0:
            stubs.append(f"  def {fn['name']}, do: :erlang.nif_error(:nif_not_loaded)")
        else:
            stubs.append(f"  def {fn['name']}({args}), do: :erlang.nif_error(:nif_not_loaded)")
    body = "\n".join(stubs)
    return f"""defmodule {name} do
  @moduledoc \"\"\"
  Generated from `tools/dsl/decls.json`. User code is `{module["user"]}`.
  \"\"\"

  @on_load :load_nif

  def load_nif do
    case :erlang.load_nif(Mojoler.Nif.path("{lib}"), 0) do
      :ok -> Mojoler.Nif.mark!("{lib}")
      other -> other
    end
  end

{body}
end
"""


def render(data: dict) -> dict[str, str]:
    files = {}
    for module in data["modules"]:
        kinds = [fn["kind"] for fn in module["functions"]]
        if kinds == ["add"]:
            mojo = arith(module)
        elif kinds == ["shift", "borrow_len"]:
            mojo = bytes_mod(module)
        elif kinds == ["open", "bump"]:
            mojo = box(module)
        else:
            fail(f"no template for {kinds}")
        files[module["source"]] = mojo if mojo.endswith("\n") else mojo + "\n"
        ex = elixir(module)
        files[module["elixir"]] = ex if ex.endswith("\n") else ex + "\n"
    return files


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--decls", type=Path, default=ROOT / "tools/dsl/decls.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = render(load(args.decls))
    if args.check:
        bad = False
        for rel, text in files.items():
            path = ROOT / rel
            current = path.read_text() if path.exists() else ""
            if current != text:
                bad = True
                diff = difflib.unified_diff(
                    current.splitlines(True),
                    text.splitlines(True),
                    fromfile=str(path),
                    tofile=rel,
                )
                sys.stderr.writelines(diff)
        if bad:
            fail("generated files differ; run tools/dsl/generate.py")
        print("dsl mojo: matches")
        return
    for rel, text in files.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
